"""Regenerate ML/vimaan_nlu/command_words.txt (the offline recogniser's
grammar) from the training schema. Run after changing schema_config.py or the
generator's prefixes/suffixes.

Usage::

    python scripts/build_stt_vocabulary.py           # write the file
    python scripts/build_stt_vocabulary.py --check   # exit 1 if out of date
"""

from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path[:0] = [os.path.join(ROOT, "ML"), os.path.join(ROOT, "ML", "config")]

from config.schema_config import SCHEMA  # noqa: E402
from vimaan_nlu.stt_vocabulary import (  # noqa: E402
    VOCABULARY_FILE,
    build_vocabulary,
    load_vocabulary,
)

# Kept in sync with ML/data/generate_slot_dataset.py (importing it pulls in
# the training utils).
PREFIXES = ["please", "could you", "request", "confirm", "go ahead and"]
SUFFIXES = ["now", "immediately", "for me", "if you would"]
HEADER = "# Generated by scripts/build_stt_vocabulary.py from ML/config/schema_config.py — do not edit.\n"


def expected() -> list[str]:
    return build_vocabulary(SCHEMA, PREFIXES + SUFFIXES)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    words = expected()
    if args.check:
        current = load_vocabulary() if os.path.exists(VOCABULARY_FILE) else []
        if current != words:
            print(f"{VOCABULARY_FILE} is out of date; run {__file__}", file=sys.stderr)
            return 1
        return 0
    with open(VOCABULARY_FILE, "w", encoding="utf-8") as fh:
        fh.write(HEADER + "\n".join(words) + "\n")
    print(f"wrote {len(words)} words to {VOCABULARY_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
