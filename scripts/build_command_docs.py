"""Write docs/COMMANDS.md (every voice command) from the command table.

Usage::

    python scripts/build_command_docs.py           # write the file
    python scripts/build_command_docs.py --check   # exit 1 if out of date
"""

from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "ML"))

from vimaan_nlu.commands import COMMANDS, SLOT_DISPLAY, SLOT_VALIDATORS, Command  # noqa: E402
from vimaan_nlu.slot_types import Range  # noqa: E402

OUTPUT = os.path.join(ROOT, "docs", "COMMANDS.md")

# Example values used to fill templates in the docs.
EXAMPLES = {
    "degrees": "two seven zero",
    "altitude": "seven thousand",
    "flight_level": "three five zero",
    "frequency": "one two one decimal five",
    "com_port": "one",
}
SAFETY_TEXT = {
    "gear_up_low_altitude": "gear up below 1,000 ft AGL",
    "engine_shutdown_in_flight": "shutdown while airborne",
    "parking_brake_at_speed": "set above 5 kt ground speed",
}


def example(c: Command, template: str) -> str:
    text = template
    for name, slot in c.slots.items():
        value = EXAMPLES.get(name)
        if value is None:
            value = next(iter(slot.values))
        text = text.replace("{" + name + "}", value)
    return text


def values(c: Command) -> str:
    parts = []
    for name, slot in c.slots.items():
        v = SLOT_VALIDATORS.get(name)
        if name == "state":
            parts.append(" / ".join(dict.fromkeys(str(x) for x in slot.values)))
        elif isinstance(v, Range):
            fmt = (lambda x: str(int(x))) if v.integer else str
            parts.append(f"{SLOT_DISPLAY.get(name, name)} {fmt(v.lo)}–{fmt(v.hi)}")
        else:
            parts.append(name)
    return "; ".join(parts) or "—"


def render() -> str:
    out = [
        "# Voice commands",
        "",
        "Generated by `scripts/build_command_docs.py` from",
        "[`ML/vimaan_nlu/commands.py`](../ML/vimaan_nlu/commands.py), do not edit.",
        "Hold push-to-talk (Z), say the command, release.",
        "",
        "## Actions",
        "",
        "| Command | Say | Values | Needs the word | Asks to confirm | X-Plane |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for c in COMMANDS:
        if not c.actionable:
            continue
        say = "<br>".join(f'"{example(c, t)}"' for t in c.templates[:3])
        words = ", ".join(sorted(c.command_words))
        safety = ", ".join(SAFETY_TEXT.get(r, r) for r in c.safety) or "—"
        sim = "<br>".join(f"`{b}`" for b in c.bindings)
        out.append(f"| {c.display} | {say} | {values(c)} | {words} | {safety} | {sim} |")
    out += [
        "",
        "## Conversation",
        "",
        "| Intent | Say | Reply |",
        "| --- | --- | --- |",
    ]
    for c in COMMANDS:
        if c.actionable:
            continue
        say = "<br>".join(f'"{t}"' for t in c.templates[:2])
        out.append(f"| {c.display} | {say} | {c.reply or '(silent)'} |")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else ""
        if current != text:
            print(f"{OUTPUT} is out of date; run {__file__}", file=sys.stderr)
            return 1
        return 0
    with open(OUTPUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
