BY_INTENT: Mapping[str, Command] = MappingProxyType({c.intent: c for c in COMMANDS})


def command(intent: str) -> Command | None:
    return BY_INTENT.get(intent)


def actionable() -> tuple[Command, ...]:
    return tuple(c for c in COMMANDS if c.actionable)


def training_schema() -> dict[str, dict[str, Any]]:
    """The generator's schema (the shape of the old ``schema_config.SCHEMA``)."""
    out: dict[str, dict[str, Any]] = {}
    for c in COMMANDS:
        out[c.intent] = {
            "templates": list(c.templates),
            "slots": {name: slot.schema() for name, slot in c.slots.items()},
        }
    return out


def required_slots() -> dict[str, tuple[str, ...]]:
    return {c.intent: c.required for c in COMMANDS if c.actionable}


def command_words() -> dict[str, frozenset[str]]:
    return {c.intent: c.command_words for c in COMMANDS if c.command_words}


def self_test_probes() -> tuple[tuple[str, str], ...]:
    return tuple((c.self_test, c.intent) for c in COMMANDS if c.self_test)


def all_bindings() -> set[str]:
    return {b for c in COMMANDS for b in c.bindings}
