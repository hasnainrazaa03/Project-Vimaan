def _autopilot_unit(n: str) -> dict[str, Any]:
    s = "" if n == "1" else n
    return {
        "dataref": f"sim/cockpit2/autopilot/servos{s}_on",
        "on_cmd": f"sim/autopilot/servos{s}_on",
        "off_cmd": None,
        "toggle": f"sim/autopilot/servos{s}_toggle",
        # The panel's AP button is the toggle, and every aircraft honours it;
        # the A330 ignored servos_on in flight. With the state readable, the
        # toggle is pressed only when a change is needed.
        "prefer_toggle": True,
        # An aircraft's own engage button, if its profile has one (737 CMD A/B).
        "engage_role": "autopilot_engage" if n == "1" else "autopilot2_engage",
        "label": f"Autopilot {n}",
    }


def _fd_unit(n: str) -> dict[str, Any]:
    s = "" if n == "1" else n
    return {
        "dataref": f"sim/cockpit2/autopilot/flight_director{s}_mode",
        "writable": True,
        "on_cmd": f"sim/autopilot/fdir{s}_on",
        "off_cmd": None,
        "toggle": f"sim/autopilot/fdir{s}_toggle",
        "label": f"Flight Director {n}",
    }


def _engine_unit(n: str) -> dict[str, Any]:
    return {
        "index": int(n) - 1,
        "starter": f"sim/starters/engage_starter_{n}",
        "shutdown": f"sim/starters/shut_down_{n}",
        "label": f"Engine {n}",
    }


def _names(params: Mapping[str, Any]) -> tuple[str, ...]:
    return tuple(
        v
        for unit in params["instances"].values()
        for v in unit.values()
        if isinstance(v, str) and v.startswith("sim/")
    )


