BY_INTENT: Mapping[str, Command] = MappingProxyType({c.intent: c for c in COMMANDS})


def command(intent: str) -> Command | None:
    return BY_INTENT.get(intent)


def actionable() -> tuple[Command, ...]:
    return tuple(c for c in COMMANDS if c.actionable)


def training_schema(questions: bool | None = None) -> dict[str, dict[str, Any]]:
    """Intent -> templates + slots in the legacy schema shape. ``questions``:
    True for the Tier 4 questions only, False for everything else, None for all."""
    return {
        c.intent: {
            "templates": list(c.templates),
            "slots": {name: slot.schema() for name, slot in c.slots.items()},
        }
        for c in COMMANDS
        if questions is None or c.is_question == questions
    }


def required_slots() -> dict[str, tuple[str, ...]]:
    """Slots a handler (or a question's answer) can't do without."""
    return {c.intent: c.required for c in COMMANDS if c.actionable or c.is_question}


def command_words() -> dict[str, frozenset[str]]:
    return {c.intent: c.command_words for c in COMMANDS if c.command_words}


def choice_synonyms() -> dict[str, dict[str, dict[str, tuple[str, ...]]]]:
    """intent -> choice slot -> value -> verbs that imply it."""
    return {
        c.intent: {
            name: dict(slot.synonyms) for name, slot in c.slots.items() if slot.kind == "choice"
        }
        for c in COMMANDS
        if any(slot.kind == "choice" for slot in c.slots.values())
    }


def self_test_probes() -> tuple[tuple[str, str], ...]:
    return tuple((c.self_test, c.intent) for c in COMMANDS if c.self_test)


def all_bindings() -> set[str]:
    return {b for c in COMMANDS for b in c.bindings}
