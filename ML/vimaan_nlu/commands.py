"""The command table: the single source of truth for every voice command.

Each ``Command`` says how pilots phrase it (training templates and slot
values), which values are valid, which words must be present before acting,
which plugin handler executes it and with what X-Plane bindings, which safety
rules gate it, what the self-test asks, and how the overlay names it.
Everything else is derived from this table:

- ``config/schema_config.SCHEMA`` (training data generator) — ``training_schema()``
- ``validators.SLOT_VALIDATORS`` / ``COMMAND_WORDS``
- ``safety`` (which rules apply to which intent)
- the plugin's intent -> handler map, required slots, spoken replies for
  non-actionable intents, self-test probes
- the overlay's display names
- the offline recogniser's vocabulary (``scripts/build_stt_vocabulary.py``)
- ``scripts/check_xplane_refs.py`` and ``docs/COMMANDS.md``

It lives in ``vimaan_nlu`` because that package is what the installer ships
to X-Plane. Pure Python: no torch, no X-Plane.

Adding a command (tiers T1–T4 in docs/PHASE_PLAN.md) means adding an entry
here, then data, a model, and (if no generic handler fits) a plugin handler.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from types import MappingProxyType
from typing import Any

from vimaan_nlu.slot_types import Enum, Range

# Phrase variations the training generator wraps every template in.
PREFIXES: tuple[str, ...] = ("", "please", "could you", "request", "confirm", "go ahead and")
SUFFIXES: tuple[str, ...] = ("", "now", "immediately", "for me", "if you would")

DYNAMIC = "<DYNAMIC>"  # value generated by the data generator (frequencies)

# Valid values per slot name (shared by every intent that uses the slot).
SLOT_VALIDATORS: Mapping[str, Range | Enum] = MappingProxyType(
    {
        "altitude": Range(1000, 50000),
        "degrees": Range(0, 360, wrap=True),
        "flight_level": Range(10, 430),
        "frequency": Range(118.0, 137.0, integer=False),
        "com_port": Range(1, 4),
        "state": Enum(("on", "off", "up", "down")),
    }
)

# How the overlay labels a slot value ("hdg 270", "COM 1"). "state" values
# are shown on their own ("ON").
SLOT_DISPLAY: Mapping[str, str] = MappingProxyType(
    {
        "degrees": "hdg",
        "altitude": "alt",
        "flight_level": "FL",
        "frequency": "freq",
        "com_port": "COM",
    }
)


def _frozen(d: Mapping[str, Any] | None = None) -> Mapping[str, Any]:
    return MappingProxyType(dict(d or {}))


@dataclass(frozen=True)
class Slot:
    """How a slot appears in training data."""

    kind: str  # "numerical" | "categorical"
    values: Iterable[str | int]  # training values (a range is fine), or (DYNAMIC,)
    synonyms: Mapping[str, tuple[str, ...]] = field(default_factory=_frozen)

    def schema(self) -> dict[str, Any]:
        out: dict[str, Any] = {"type": self.kind, "values": [str(v) for v in self.values]}
        if self.synonyms:
            out["synonyms"] = {k: list(v) for k, v in self.synonyms.items()}
        return out


@dataclass(frozen=True)
class Command:
    intent: str
    display: str  # shown in the overlay ("Heading", "Autopilot 1")
    templates: tuple[str, ...]
    slots: Mapping[str, Slot] = field(default_factory=_frozen)
    # Slots the handler cannot act without (self-test checks they're extracted).
    required: tuple[str, ...] = ()
    # At least one must be in the utterance before acting (fragment guard).
    command_words: frozenset[str] = frozenset()
    # Plugin method that executes it; None = not actionable (conversation).
    handler: str | None = None
    # Spoken acknowledgement for a non-actionable intent (None = stay silent).
    reply: str | None = None
    # Names of rules in safety.RULES that may require a spoken confirmation.
    safety: tuple[str, ...] = ()
    # Ctrl-Z self-test utterance (text only, nothing is actuated).
    self_test: str | None = None
    # Handler parameters, including the X-Plane datarefs/commands it uses.
    params: Mapping[str, Any] = field(default_factory=_frozen)
    # Every X-Plane dataref/command this command touches (checked against
    # X-Plane's lists by scripts/check_xplane_refs.py and the fake sim).
    bindings: tuple[str, ...] = ()

    @property
    def actionable(self) -> bool:
        return self.handler is not None


_ON_OFF_AP = {"on": ("engage", "activate"), "off": ("disengage", "deactivate")}
_ON_OFF_FD = {"on": ("enable", "activate"), "off": ("disable", "deactivate")}
_ON_OFF_ENGINE = {"on": ("start", "ignite"), "off": ("stop", "shut down", "kill")}


def _state(values: tuple[str, ...], synonyms: Mapping[str, tuple[str, ...]]) -> Slot:
    return Slot("categorical", values, _frozen(synonyms))


def _autopilot(unit: int, word: str) -> Command:
    n = "" if unit == 1 else str(unit)
    return Command(
        intent=f"toggle_autopilot_{unit}",
        display=f"Autopilot {unit}",
        templates=(
            f"autopilot {unit} {{state}}",
            f"{{state}} autopilot {unit}",
            f"ap {word} {{state}}",
        ),
        slots=_frozen({"state": _state(("on", "off"), _ON_OFF_AP)}),
        required=("state",),
        command_words=frozenset({"autopilot", "pilot", "ap"}),
        handler="_toggle_binary",
        self_test="engage autopilot one" if unit == 1 else None,
        # X-Plane has no "servos off" command: "off" uses the toggle, but only
        # after reading the state, so it can never turn the autopilot on.
        params=_frozen(
            {
                "dataref": f"sim/cockpit2/autopilot/servos{n}_on",
                "on_cmd": f"sim/autopilot/servos{n}_on",
                "off_cmd": None,
                "toggle": f"sim/autopilot/servos{n}_toggle",
                "label": f"Autopilot {unit}",
            }
        ),
        bindings=(
            f"sim/cockpit2/autopilot/servos{n}_on",
            f"sim/autopilot/servos{n}_on",
            f"sim/autopilot/servos{n}_toggle",
        ),
    )


def _flight_director(unit: int, word: str) -> Command:
    n = "" if unit == 1 else str(unit)
