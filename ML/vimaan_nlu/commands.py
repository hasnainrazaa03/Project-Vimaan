"""The command table: the single source of truth for every voice command.

Each ``Command`` says how pilots phrase it (training templates and typed
slots), which values are valid, which words must be present before acting,
which plugin handler executes it and with what X-Plane bindings, which safety
rules gate it, what the self-test asks, and how the overlay names it.
Everything else is derived from this table:

- the training data generator (``ML/data/generate_v2.py``) and
  ``config/schema_config.SCHEMA`` (``training_schema()``, used by the
  vocabulary builder and the legacy data scripts)
- ``validators.SLOT_VALIDATORS`` / ``COMMAND_WORDS``
- the postprocessor's verb -> value maps (``choice_synonyms()``)
- ``safety`` (which rules apply to which intent)
- the plugin's intent -> handler map, bindings, required slots, spoken replies
  for non-actionable intents, self-test probes
- the overlay's display names
- the offline recogniser's vocabulary (``scripts/build_stt_vocabulary.py``)
- ``scripts/check_xplane_refs.py`` and ``docs/COMMANDS.md``

It lives in ``vimaan_nlu`` because that package is what the installer ships
to X-Plane. Pure Python: no torch, no X-Plane.

Templates use placeholders the generator fills: ``{slot}`` with the slot's
spoken value ("two seven zero", "up", "one"), ``{slot_verb}`` with a verb
that implies a choice ("raise" -> up, "disconnect" -> off), and
``{instance_ord}`` with an ordinal/side ("second", "left").
"""

